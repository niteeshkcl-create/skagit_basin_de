nc_files = sorted(glob.glob(os.path.join(data_dir, "auxhist_*.nc")))
print(f"Found {len(nc_files)} NetCDF files")
print(f"Date range: {os.path.basename(nc_files[0])} to {os.path.basename(nc_files[-1])}\n")

# ============================================================================
# STEP 4: Process each station
# ============================================================================
print("=" * 80)
print("STEP 4: Processing all stations...")
print("=" * 80)

for station_id, station_name, station_lat, station_lon in stations:
    print(f"\nProcessing Station {station_id}: {station_name}")
    print("-" * 60)

    i, j, lat, lon, name = station_indices[station_id]
    all_dfs = []

    # Process each NetCDF file for this station
    for file_idx, nc_file in enumerate(nc_files):
        if file_idx % 200 == 0:  # Print progress every 200 files                                                                                          
            print(f"  Files processed: {file_idx}/{len(nc_files)}", end="\r")

        try:
            ds = xr.open_dataset(nc_file)

            # Parse times - WRF format: YYYY-MM-DD_HH:MM:SS
            times = ds['Times'].values
            if len(times.shape) > 1:
                times = times.flatten()

            times_dt = []
            for t in times:
                if isinstance(t, bytes):
                    time_str = t.decode('utf-8')
                else:
                    time_str = str(t)
                time_dt = datetime.strptime(time_str, '%Y-%m-%d_%H:%M:%S')
                times_dt.append(time_dt)

            # Extract data for this station
            records = []
            for time_idx, time_dt in enumerate(times_dt):
                record = {
                    'datetime': time_dt,
                    'date': time_dt.date(),
                    'hour': time_dt.hour,
                    'station_id': station_id,
                    'lat': lat,
                    'lon': lon,
                }

                for var in variables_of_interest:
                    if var in ds:
                        try:
                            value = ds[var].isel(Time=time_idx, south_north=j, west_east=i).values
                            record[var] = float(value)
                        except:
                            record[var] = np.nan

                records.append(record)

            df = pd.DataFrame(records)
            all_dfs.append(df)
            ds.close()

        except Exception as e:
            print(f"  Error reading {os.path.basename(nc_file)}: {e}")
            continue

    # ========================================================================
    # STEP 5: Concatenate and process data for this station
    # ========================================================================
    if all_dfs:
        print(f"  \nConcatenating {len(all_dfs)} files...", end=" ")
        combined_df = pd.concat(all_dfs, ignore_index=True)
        combined_df = combined_df.sort_values('datetime').reset_index(drop=True)
        print(f"✓ ({len(combined_df)} records)")

        # Format datetime
        combined_df['datetime'] = combined_df['datetime'].dt.strftime('%Y-%m-%d %H:00:00')
        combined_df['datetime'] = pd.to_datetime(combined_df['datetime'])

        # Calculate actual precipitation (cumulative → hourly)
        combined_df['RAINC'] = combined_df['RAINC'].diff()
        combined_df['RAINNC'] = combined_df['RAINNC'].diff()
        combined_df['PRECIP_TOTAL'] = combined_df['RAINC'] + combined_df['RAINNC']
        combined_df['PRECIP_TOTAL'] = combined_df['PRECIP_TOTAL'] / 1000  # Convert from mm to m

        # Convert temperature from Kelvin to Celsius
        combined_df['T2_C'] = combined_df['T2'] - 273.15

        # Calculate wind speed from U10 and V10 components
        combined_df['WIND_SPEED'] = np.sqrt(combined_df['U10']**2 + combined_df['V10']**2)

        # Calculate relative humidity using Magnus formula
        e = (combined_df['Q2'] * combined_df['PSFC']) / (0.622 + combined_df['Q2'] * 0.378)
        T_c = combined_df['T2_C']
        e_s = 611.2 * np.exp((17.62 * T_c) / (T_c + 243.12))
        combined_df['RH'] = (100.0 * (e / e_s)).clip(0, 100)

        # Drop the first row (has NaN for precipitation)
        combined_df = combined_df.drop(combined_df.index[0]).reset_index(drop=True)

        # ====================================================================
        # STEP 6: Save as CSV and DHSVM format
        # ====================================================================

        # Save as CSV
        csv_file = os.path.join(output_csv_dir, f"station_{station_id}_combined.csv")
        combined_df.to_csv(csv_file, index=False)

        # Save as DHSVM format (space-separated with specific decimal places)
        combined_df['datetime_formatted'] = combined_df['datetime'].dt.strftime('%m/%d/%Y-%H:%M:%S')

        output_df = pd.DataFrame({
            'datetime': combined_df['datetime_formatted'],
            'T2_C': combined_df['T2_C'].apply(lambda x: f"{x:.3f}"),
            'WIND_SPEED': combined_df['WIND_SPEED'].apply(lambda x: f"{x:.3f}"),
            'RH': combined_df['RH'].apply(lambda x: f"{x:.3f}"),
            'SWDNB': combined_df['SWDNB'].apply(lambda x: f"{x:.3f}"),
            'LWDNB': combined_df['LWDNB'].apply(lambda x: f"{x:.3f}"),
            'PRECIP_TOTAL': combined_df['PRECIP_TOTAL'].apply(lambda x: f"{x:.6f}")
        })

        dhsvm_file = os.path.join(output_dhsvm_dir, f"data_{lat}_{lon}")
        output_df.to_csv(dhsvm_file, sep=' ', header=False, index=False)

        print(f"  ✓ Saved CSV: {csv_file}")
        print(f"  ✓ Saved DHSVM: {dhsvm_file}")
        print(f"  Date range: {combined_df['datetime'].min()} to {combined_df['datetime'].max()}")
    else:
        print(f"  ✗ No data extracted for station {station_id}")

print("\n" + "=" * 80)
print("PROCESSING COMPLETE!")
print("=" * 80)
